import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const out = join(root, 'services', 'db', 'migrations.gen.ts');

function load(dialect: string) {
  const dir = join(root, 'migrations', dialect);
  return readdirSync(dir)
    .filter((f) => /^\d{4}_.+\.sql$/.test(f))
    .sort()
    .map((f) => {
      const version = Number.parseInt(f.slice(0, 4), 10);
      return `    { version: ${version}, name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))} },`;
    });
}

const sqlite = load('sqlite');
const postgres = load('postgres');
if (sqlite.length !== postgres.length) {
  throw new Error(`migration count differs: sqlite=${sqlite.length} postgres=${postgres.length}`);
}

const body = `// GENERATED by scripts/gen-migrations.ts from migrations/. Do not edit.
import type { Dialect } from "./driver";

export interface Migration {
  version: number;
  name: string;
  sql: string;
}

export const MIGRATIONS: Record<Dialect, Migration[]> = {
  sqlite: [
${sqlite.join('\n')}
  ],
  postgres: [
${postgres.join('\n')}
  ],
};
`;

writeFileSync(out, body);
console.log(`wrote ${sqlite.length} migration(s) per dialect to services/db/migrations.gen.ts`);
